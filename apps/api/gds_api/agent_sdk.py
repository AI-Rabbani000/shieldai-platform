"""Common Agent SDK: the assess/plan/execute/validate/report contract every runtime
agent implements. Phase 3 has exactly one implementer - Rabbani AI Core's activities in
gds_api/workflows/activities.py - so this stays a plain Protocol inside apps/api rather
than a separate packages/agent-sdk package. Extract it when Phase 4's Foundation Agents
are a second real consumer (see packages/README.md)."""

from typing import Any, Protocol


class Agent(Protocol):
    async def assess(self, context: dict[str, Any]) -> dict[str, Any]: ...
    async def plan(self, context: dict[str, Any]) -> dict[str, Any]: ...
    async def execute(self, plan: dict[str, Any]) -> dict[str, Any]: ...
    async def validate(self, result: dict[str, Any]) -> dict[str, Any]: ...
    async def report(self, result: dict[str, Any]) -> str: ...
